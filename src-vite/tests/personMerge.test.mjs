import test from "node:test";
import assert from "node:assert/strict";
import { readFile } from "node:fs/promises";
import ts from "typescript";

const source = await readFile(
  new URL("../src/common/personMerge.ts", import.meta.url),
  "utf8",
);
const exports = {};
new Function(
  "exports",
  ts.transpile(source, {
    target: ts.ScriptTarget.ES2022,
    module: ts.ModuleKind.CommonJS,
  }),
)(exports);

const {
  isAutoGeneratedPersonName,
  resolveMergedPersonName,
  remapSmartAlbumPersonIds,
} = exports;

test("isAutoGeneratedPersonName detects empty and default Person N placeholders", () => {
  assert.equal(isAutoGeneratedPersonName(""), true);
  assert.equal(isAutoGeneratedPersonName("   "), true);
  assert.equal(isAutoGeneratedPersonName(null), true);
  assert.equal(isAutoGeneratedPersonName("Person 1"), true);
  assert.equal(isAutoGeneratedPersonName("person 42"), true);
  assert.equal(isAutoGeneratedPersonName("Pet 2"), true);
  assert.equal(isAutoGeneratedPersonName("pet 10"), true);
  assert.equal(isAutoGeneratedPersonName("Person"), false);
  assert.equal(isAutoGeneratedPersonName("Pet"), false);
  assert.equal(isAutoGeneratedPersonName("Alice"), false);
  assert.equal(isAutoGeneratedPersonName("Person 1 Jr"), false);
});

test("resolveMergedPersonName keeps target name or adopts custom source name over placeholder", () => {
  assert.equal(resolveMergedPersonName("Person 12", "Sarah"), "Sarah");
  assert.equal(resolveMergedPersonName("Bob", "Sarah"), "Sarah");
  assert.equal(resolveMergedPersonName("Sarah", "Person 12"), "Sarah");
  assert.equal(resolveMergedPersonName("Rory", "Pet 2"), "Rory");
  assert.equal(resolveMergedPersonName("Pet 2", "Rory"), "Rory");
  assert.equal(resolveMergedPersonName("Sarah", ""), "Sarah");
  assert.equal(resolveMergedPersonName("Person 12", "Person 3"), "Person 3");
  assert.equal(resolveMergedPersonName(null, null), "");
});

test("remapSmartAlbumPersonIds rewrites merged person rule values without touching unrelated rules", () => {
  const smartAlbums = [
    {
      id: "sa-1",
      name: "Family trips",
      query: {
        version: 1,
        match: "all",
        rules: [
          { id: "r1", field: "person", operator: "has", value: 7 },
          { id: "r2", field: "person", operator: "not_has", value: 9 },
          { id: "r3", field: "tag", operator: "has", value: 7 },
          { id: "r4", field: "person", operator: "empty", value: null },
        ],
      },
    },
    {
      id: "sa-2",
      name: "Favorites",
      query: {
        version: 1,
        match: "all",
        rules: [{ id: "r5", field: "favorite", operator: "is", value: true }],
      },
    },
  ];

  const { albums, changed } = remapSmartAlbumPersonIds(smartAlbums, [7], 2);
  assert.equal(changed, true);
  assert.equal(albums[0].query.rules[0].value, 2);
  assert.equal(albums[0].query.rules[1].value, 9);
  assert.equal(albums[0].query.rules[2].value, 7);
  assert.equal(albums[0].query.rules[3].value, null);
  assert.equal(albums[1], smartAlbums[1]);
  // Original untouched
  assert.equal(smartAlbums[0].query.rules[0].value, 7);

  const noOp = remapSmartAlbumPersonIds(smartAlbums, [99], 2);
  assert.equal(noOp.changed, false);
  assert.equal(noOp.albums, smartAlbums);
});
